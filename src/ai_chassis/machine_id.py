"""The durable provenance machine id (install.sh's retired Steps 1b3 and 1b3a).

``AI_MACHINE_ID`` answers "which box is this", which ``AI_HOST`` cannot: ``AI_HOST`` is a
mutable, readable profile name, while this value is 128 random bits, so the alias
``scripts/provenance_identity.py`` publishes from it is non-reversible by construction. The
resolver reads the value from ``$XDG_CONFIG_HOME/ai-harness/machine.toml`` at call time, because
an export in ``~/.bashrc`` never reaches a non-interactive shell; the variable is the fallback.
The raw value is the pre-image of the published alias, so it is never printed.
"""

from __future__ import annotations

import os
import re
import secrets
import sys
import tempfile
import tomllib
from collections.abc import Mapping
from pathlib import Path

from .profile import persist_exported_var

#: The profiles Step 1b3 read for an existing export, in its order.
PROFILE_FILES = (".bashrc", ".zshenv")
#: Owner-only: the file holds the pre-image of the published machine alias.
OWNER_ONLY = 0o600
_EXPORT = re.compile(r"^\s*export\s+AI_MACHINE_ID=(.*)$")
_CONFIG_HEADER = (
    "# ai-harness machine identity (ISSUE-REF). Generated by install.sh.\n"
    "# Read at call time by scripts/provenance_identity.py, so an edit here takes\n"
    "# effect WITHOUT restarting a Claude Code session.\n"
    "# Owner-only: the pre-image of the published machine alias. Never commit it.\n"
)


def _declared(path: Path) -> str:
    """The file's last ``export AI_MACHINE_ID=`` value, quotes removed; "" when it has none."""
    if not os.access(path, os.R_OK):
        return ""
    try:
        text = path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return ""
    values = [m[1] for line in text.split("\n") if (m := _EXPORT.match(line))]
    return values[-1].replace('"', "").replace("'", "") if values else ""


def provision(home: Path, environ: Mapping[str, str]) -> str | None:
    """Step 1b3: the effective id, generating and persisting one when none exists.

    Returns ``None`` on a conflict (two profiles, or the environment and a profile, disagree):
    nothing is written and the warning names the files, never the values.
    """
    files = [home / name for name in PROFILE_FILES]
    ambient = environ.get("AI_MACHINE_ID", "")
    seen = ""
    conflict = False
    for path in files:
        value = _declared(path)
        if not value:
            continue
        if seen and value != seen:
            conflict = True
        seen = value
    if ambient and seen and ambient != seen:
        conflict = True
    if conflict:
        print(
            "  [WARN] AI_MACHINE_ID disagrees between the environment and/or profile files.\n"
            "         Values are deliberately not printed (they are the pre-image of the\n"
            "         published machine alias). Resolve by hand so ONE value remains in\n"
            f"         {' '.join(str(path) for path in files)}, then re-run. Not overwriting.",
            file=sys.stderr,
        )
        return None
    if ambient or seen:
        print("  [ok]  AI_MACHINE_ID already provisioned (opaque, not printed)")
        return ambient or seen
    generated = f"m-{secrets.token_hex(16)}"
    persist_exported_var("AI_MACHINE_ID", generated, home=home, environ=environ)
    print("  [set] AI_MACHINE_ID generated (opaque, not printed)")
    return generated


def config_path(home: Path, environ: Mapping[str, str]) -> Path:
    """``${XDG_CONFIG_HOME:-$HOME/.config}/ai-harness/machine.toml``."""
    root = environ.get("XDG_CONFIG_HOME") or str(home / ".config")
    return Path(root) / "ai-harness" / "machine.toml"


def _recorded_id(path: Path) -> str | None:
    """``[machine].id`` as the resolver would read it; None for a missing or unparsable file.

    Parsed, not substring-matched: a commented-out ``id = "..."`` line matched the shell's grep
    while the resolver read no id at all.
    """
    try:
        data = tomllib.loads(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, tomllib.TOMLDecodeError):
        return None
    table = data.get("machine")
    recorded = table.get("id") if isinstance(table, dict) else None
    return recorded if isinstance(recorded, str) else None


def _tighten_mode(path: Path) -> None:
    """An already-current file is still the alias's pre-image, so it is kept owner-only."""
    try:
        if path.stat().st_mode & 0o777 == OWNER_ONLY:
            return
        path.chmod(OWNER_ONLY)
    except OSError:
        print(
            f"  [WARN] could not make {path} owner-only (0600)",
            file=sys.stderr,
        )
        return
    print("  [ok]  machine.toml mode tightened to 0600")


def write_config(value: str, home: Path, environ: Mapping[str, str]) -> None:
    """Step 1b3a: mirror ``value`` into machine.toml, atomically and owner-only.

    Written on the already-provisioned path too: a machine provisioned before the file existed
    otherwise never grows one. Every failure is a warning, as in the shell: provenance then
    records an unknown machine, and the install goes on.
    """
    path = config_path(home, environ)
    directory = path.parent
    try:
        directory.mkdir(parents=True, exist_ok=True)
    except OSError:
        print(
            f"  [WARN] could not create {directory}; Authoring-machine stays unknown",
            file=sys.stderr,
        )
        return
    if _recorded_id(path) == value:
        print("  [ok]  machine.toml already current (opaque, not printed)")
        _tighten_mode(path)
        return
    try:
        descriptor, staged_name = tempfile.mkstemp(
            prefix=".machine.toml.", dir=directory
        )
    except OSError:
        print(
            f"  [WARN] no writable temp file in {directory}; machine.toml unchanged",
            file=sys.stderr,
        )
        return
    staged = Path(staged_name)
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8") as stream:
            stream.write(f'{_CONFIG_HEADER}[machine]\nid = "{value}"\n')
        staged.chmod(OWNER_ONLY)
        os.replace(staged, path)
    except OSError:
        staged.unlink(missing_ok=True)
        print(
            f"  [WARN] could not write {path}; Authoring-machine stays unknown",
            file=sys.stderr,
        )
        return
    print("  [set] machine.toml written (opaque, not printed)")
