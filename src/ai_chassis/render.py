"""Deterministic context renderer and legacy compiler compatibility API."""

import argparse
import json
import os
import re
from dataclasses import dataclass
from importlib.metadata import PackageNotFoundError, version
from pathlib import Path

from .compose import (
    DEFAULT_MODULES,
    Explanation,
    resolve_values,
    validate_packaged_default,
    validate_replacements,
)
from .config import ConfigValidationError, LoadedConfig, load_config
from .decision_routing import investigate_family, investigate_line
from .fingerprint import (
    config_identity,
    consumed_snapshot,
    inputs_fingerprint,
)
from .machine_registry import machine_names

DO_NOT_EDIT = "<!-- DO NOT EDIT — generated by compile.py from module files. Edit source modules instead. -->\n\n"
SHARED_BASE = "agents-base.md"
AGENT_OUTPUT_PREFIX = {"claude": "CLAUDE", "gemini": "GEMINI"}

_TIER_MARKER_RE = re.compile(
    r"^[ \t]*<!--[ \t]*(?:\[(?:STABLE|VOLATILE|CONTEXT)\]|Tier legend.*)[ \t]*-->[ \t]*$",
    re.MULTILINE,
)
_PUBLIC_DEFAULTS = Path(__file__).parent / "defaults"
_PUBLIC_SETTINGS = {"agents": ["claude"], "machines": []}


@dataclass(frozen=True)
class RenderPlan:
    outputs: dict[str, bytes]
    config_identity: str | None
    inputs_fingerprint: str | None
    consumed_paths: tuple[Path, ...]
    explanations: dict[str, Explanation]


def _strip_tier_markers(text: str) -> str:
    return re.sub(r"\n{3,}", "\n\n", _TIER_MARKER_RE.sub("", text))


def _assemble(parts: list[str]) -> str:
    return (
        DO_NOT_EDIT
        + _strip_tier_markers("\n\n".join(part.strip("\n") for part in parts))
        + "\n"
    )


def _read_required(path: Path) -> str:
    if not path.exists():
        raise FileNotFoundError(f"missing {path}")
    return path.read_bytes().decode("utf-8")


def _write_if_changed(path: Path, content: bytes | str) -> bool:
    canonical = content.encode("utf-8") if isinstance(content, str) else content
    try:
        if path.read_bytes() == canonical:
            return False
    except OSError:
        pass
    path.write_bytes(canonical)
    return True


def _core_version() -> str:
    try:
        return version("ai-chassis")
    except PackageNotFoundError:
        return "0.0.0"


def _legacy_settings(
    config: LoadedConfig,
) -> tuple[list[str], list[str], dict[str, str]]:
    data = config.data
    if config.schema_version == 0:
        return (
            list(data["agents"]),
            list(data["machines"]),
            dict(data.get("overlay_aliases", {})),
        )
    site = data.get("site", {})
    # Schema 1 has no machines array: the compiled set IS the set of [machine.<name>] tables
    # (ISSUE-REF Phase 1, D-1 (d)), so the two cannot disagree. config.py refuses a leftover
    # site.machines rather than letting a stale array shadow the tables.
    return (
        list(site["agents"]),
        machine_names(data),
        dict(data.get("overlay_aliases", {})),
    )


def _setting_layers(
    config: LoadedConfig,
    machine: str | None = None,
    cli_overrides: dict[str, object] | None = None,
) -> list[tuple[str, dict[str, object], Path]]:
    machine_values = config.data.get("machine", {}).get(machine, {}) if machine else {}
    site_values = dict(config.data.get("site", {}))
    if config.schema_version >= 1:
        # The compiled machine set is derived from the [machine.<name>] tables (same file,
        # same provenance), so `explain` reports it under the private site layer.
        site_values["machines"] = machine_names(config.data)
    return [
        ("public defaults", _PUBLIC_SETTINGS, Path(__file__)),
        ("public agent delta", {}, Path(__file__)),
        ("private site config", site_values, config.path),
        ("private machine profile", machine_values, config.path),
        ("CLI overrides", cli_overrides or {}, Path("<command-line>")),
    ]


def explain_config_value(
    config_dir: Path,
    key: str,
    machine: str | None = None,
    cli_overrides: dict[str, object] | None = None,
) -> str:
    """Explain one effective schema-1 value with all shadowed provenance."""
    config = load_config(config_dir)
    return resolve_values(key, _setting_layers(config, machine, cli_overrides)).format()


def _validated_agents(value: object, label: str) -> list[str]:
    """Return the enabled agent names, failing closed on one we cannot render.

    An unknown name must name itself in the error: ``AGENT_OUTPUT_PREFIX`` is indexed
    directly when the outputs are named, so without this check a typo surfaced as a
    bare ``KeyError`` with no indication of which agent or which config key produced it.
    """
    if not isinstance(value, list) or not all(isinstance(item, str) for item in value):
        raise ValueError(f"{label} must be an array of agent names")
    unknown = [name for name in value if name not in AGENT_OUTPUT_PREFIX]
    if unknown:
        raise ConfigValidationError(
            f"{label} names unknown agent(s) {', '.join(repr(name) for name in unknown)}; "
            f"known agents are {', '.join(repr(name) for name in sorted(AGENT_OUTPUT_PREFIX))}"
        )
    return list(value)


def _module_list(value: object, label: str) -> list[Path]:
    if not isinstance(value, list) or not all(isinstance(item, str) for item in value):
        raise ValueError(f"{label} must be an array of module paths")
    return [Path(item) for item in value]


def _feature_modules(
    config: LoadedConfig, features: object, machine: str, agent: str
) -> list[Path]:
    """The ``[modules.feature.<skill>]`` modules this machine's file carries for ``agent``.

    A feature's modules are compiled only where the skill install registry beside the config
    enables the skill of the same name for the machine, so one ``enable = ["<skill>"]`` line is
    the whole switch. A missing or unreadable registry enables none.
    """
    if not isinstance(features, dict):
        raise TypeError("modules.feature must be a table of skill names")
    # Imported here: skills_install reaches this module through rendered_links.
    from .skills_install import REGISTRY_NAME, skill_enabled

    registry = config.root / REGISTRY_NAME
    paths: list[Path] = []
    for skill in sorted(features):
        table = features[skill]
        if not isinstance(table, dict):
            raise TypeError(f"modules.feature.{skill} must be a table of agent names")
        if skill_enabled(registry, machine, skill):
            paths.extend(
                _module_list(table.get(agent, []), f"modules.feature.{skill}.{agent}")
            )
    return paths


def _feature_registry_input(config: LoadedConfig, features: object) -> set[Path]:
    """The registry, when feature modules are declared: it decides which of them compile, so it
    is part of the render's identity and a flipped switch is never a cache hit."""
    from .skills_install import REGISTRY_NAME

    if features and (config.root / REGISTRY_NAME).is_file():
        return {Path(REGISTRY_NAME)}
    return set()


def _investigate_lines(
    tables: dict[str, dict], agents_by_machine: dict[str, list[str]]
) -> dict[str, str]:
    """ISSUE-REF D-5: per machine output, the generated line naming where its spikes,
    investigations and /research-doc delegate, so the prose cannot drift from the key."""
    return {
        f"{AGENT_OUTPUT_PREFIX[agent]}.{machine}.md": investigate_line(
            investigate_family(machine, tables[machine])
        )
        for machine, agents in agents_by_machine.items()
        if machine in tables
        for agent in agents
    }


def _schema1_plan(
    config: LoadedConfig,
    cli_overrides: dict[str, object] | None,
    environ: dict[str, str],
) -> RenderPlan:
    public_snapshots = {
        public_path: (_PUBLIC_DEFAULTS / Path(public_path).name).read_bytes()
        for public_path in DEFAULT_MODULES
    }
    for public_path in DEFAULT_MODULES:
        validate_packaged_default(
            _PUBLIC_DEFAULTS / Path(public_path).name,
            public_path,
            public_snapshots[public_path],
        )

    modules = config.data.get("modules", {})
    replacements = modules.get("replace", [])
    if not isinstance(replacements, list):
        raise TypeError("modules.replace must be an array of tables")
    packaged_versions = {
        path: declared[0] for path, declared in DEFAULT_MODULES.items()
    }
    validate_replacements(replacements, packaged_versions)

    explanations = {
        key: resolve_values(key, _setting_layers(config, cli_overrides=cli_overrides))
        for key in ("agents", "machines")
    }
    agents = _validated_agents(explanations["agents"].winner.value, "site.agents")
    machines = list(explanations["machines"].winner.value)
    aliases = dict(config.data.get("overlay_aliases", {}))

    # Agent enablement is per machine profile (D-11): the [machine.<name>] layer already
    # ranks above [site] in _setting_layers, so a machine that names its own `agents`
    # overrides the site list and a machine that does not inherits it.
    agents_by_machine = {
        machine: _validated_agents(
            resolve_values(
                "agents",
                _setting_layers(config, machine=machine, cli_overrides=cli_overrides),
            ).winner.value,
            f"machine.{machine}.agents",
        )
        for machine in machines
    }

    replacement_by_public = {str(item["public_path"]): item for item in replacements}
    base_paths: list[Path] = []
    default_public_path = "defaults/agents-base.md"
    use_public_default = default_public_path not in replacement_by_public
    if default_public_path in replacement_by_public:
        base_paths.append(Path(str(replacement_by_public[default_public_path]["with"])))
    base_paths.extend(_module_list(modules.get("site_base", []), "modules.site_base"))

    delta = modules.get("delta", {})
    overlays = modules.get("overlay", {})
    features = modules.get("feature", {})
    output_module_paths: dict[str, list[Path]] = {"AGENTS.md": list(base_paths)}
    for machine in machines:
        overlay_machine = aliases.get(machine, machine)
        for agent in agents_by_machine[machine]:
            agent_delta = _module_list(delta.get(agent, []), f"modules.delta.{agent}")
            overlay = _module_list(
                overlays.get(agent, {}).get(overlay_machine, []),
                f"modules.overlay.{agent}.{overlay_machine}",
            )
            output_module_paths[f"{AGENT_OUTPUT_PREFIX[agent]}.{machine}.md"] = [
                *base_paths,
                *agent_delta,
                *overlay,
                *_feature_modules(config, features, machine, agent),
            ]
    investigate_lines = _investigate_lines(
        config.data.get("machine", {}), agents_by_machine
    )

    install_targets = config.data.get("install", {}).get("target", [])
    if not isinstance(install_targets, list):
        raise TypeError("install.target must be an array of tables")
    static_sources: dict[str, Path] = {
        str(item["output"]): Path(str(item["source"]))
        for item in install_targets
        if isinstance(item, dict) and "source" in item
    }

    for output_name, source_path in static_sources.items():
        path = config.root / source_path
        if not path.is_file():
            raise FileNotFoundError(
                f"declared source for {output_name!r} is missing or unreadable: {path}"
            )

    consumed = {config.path.relative_to(config.root)}
    consumed.update(path for paths in output_module_paths.values() for path in paths)
    consumed.update(_feature_registry_input(config, features))
    consumed.update(static_sources.values())
    consumed_paths = tuple(sorted(consumed, key=lambda path: path.as_posix().encode()))
    environment_names = config.data.get("environment", {}).get("inputs", [])
    if not isinstance(environment_names, list) or not all(
        isinstance(name, str) for name in environment_names
    ):
        raise ValueError("environment.inputs must be an array of names")
    environment_inputs = {name: environ.get(name, "") for name in environment_names}
    config_relative = config.path.relative_to(config.root).as_posix()
    snapshot = consumed_snapshot(
        config.root, consumed_paths, {config_relative: config.content}
    )
    identity = config_identity(
        config.schema_version,
        snapshot.entries,
        environment_inputs,
    )
    effective_plan = json.dumps(
        [
            {
                "output": name,
                "modules": [path.as_posix() for path in paths],
                "public_default": use_public_default,
            }
            for name, paths in sorted(output_module_paths.items())
        ],
        ensure_ascii=False,
        separators=(",", ":"),
    )
    fingerprint = inputs_fingerprint(
        _core_version(),
        identity,
        environment_inputs,
        {
            "agents": json.dumps(agents, ensure_ascii=False, separators=(",", ":")),
            "resolved_agents": json.dumps(
                {machine: agents_by_machine[machine] for machine in sorted(machines)},
                ensure_ascii=False,
                separators=(",", ":"),
            ),
            "requested_machines": json.dumps(
                machines, ensure_ascii=False, separators=(",", ":")
            ),
            "resolved_machines": json.dumps(
                [aliases.get(machine, machine) for machine in machines],
                ensure_ascii=False,
                separators=(",", ":"),
            ),
            "resolved_output_plan": effective_plan,
            "static_targets": json.dumps(
                {
                    name: path.as_posix()
                    for name, path in sorted(static_sources.items())
                },
                ensure_ascii=False,
                separators=(",", ":"),
            ),
        },
    )
    public_base = public_snapshots[default_public_path].decode("utf-8")
    outputs = {}
    for name, paths in output_module_paths.items():
        parts = [public_base] if use_public_default else []
        parts.extend(
            snapshot.render_bytes[path.as_posix()].decode("utf-8") for path in paths
        )
        if name in investigate_lines:
            parts.append(investigate_lines[name])
        outputs[name] = _assemble(parts).encode("utf-8")
    for output_name, source_path in static_sources.items():
        outputs[output_name] = snapshot.render_bytes[source_path.as_posix()]
    return RenderPlan(outputs, identity, fingerprint, consumed_paths, explanations)


def _schema0_plan(config: LoadedConfig) -> RenderPlan:
    agents, machines, aliases = _legacy_settings(config)
    base = _read_required(config.root / SHARED_BASE)
    outputs = {"AGENTS.md": _assemble([base]).encode("utf-8")}
    for agent in agents:
        delta = _read_required(config.root / f"{agent}-delta.md")
        for machine in machines:
            overlay = _read_required(
                config.root / f"{agent}-{aliases.get(machine, machine)}.md"
            )
            outputs[f"{AGENT_OUTPUT_PREFIX[agent]}.{machine}.md"] = _assemble(
                [base, delta, overlay]
            ).encode("utf-8")
    return RenderPlan(outputs, None, None, (), {})


def build_render_plan(
    config_dir: Path,
    cli_overrides: dict[str, object] | None = None,
    environ: dict[str, str] | None = None,
) -> RenderPlan:
    """Compose, validate, fingerprint, and render one configuration root."""
    config = load_config(config_dir)
    if config.schema_version == 0:
        return _schema0_plan(config)
    return _schema1_plan(
        config, cli_overrides, os.environ if environ is None else environ
    )


def rendered_outputs(config_dir: Path) -> dict[str, bytes]:
    """Render all declared outputs in memory, without run-specific bytes."""
    return build_render_plan(config_dir).outputs


def render_to_directory(config_dir: Path, output_dir: Path) -> dict[str, bool]:
    output_dir.mkdir(parents=True, exist_ok=True)
    return {
        name: _write_if_changed(output_dir / name, content)
        for name, content in rendered_outputs(config_dir).items()
    }


def compile_agents_shared(
    config_dir: Path | None = None, output_dir: Path | None = None
) -> None:
    src = config_dir if config_dir is not None else Path.cwd()
    dst = output_dir if output_dir is not None else src
    changed = _write_if_changed(dst / "AGENTS.md", rendered_outputs(src)["AGENTS.md"])
    print(f"  {'compiled' if changed else 'unchanged'} -> {dst / 'AGENTS.md'}")


def compile_file(
    agent: str,
    machine: str,
    config_dir: Path | None = None,
    output_dir: Path | None = None,
    overlay_aliases: dict[str, str] | None = None,
) -> None:
    src = config_dir if config_dir is not None else Path.cwd()
    dst = output_dir if output_dir is not None else src
    _ = overlay_aliases
    name = f"{AGENT_OUTPUT_PREFIX[agent]}.{machine}.md"
    changed = _write_if_changed(dst / name, rendered_outputs(src)[name])
    print(f"  {'compiled' if changed else 'unchanged'} -> {dst / name}")


def main(
    config_dir: Path | None = None,
    output_dir: Path | None = None,
    argv: list[str] | None = None,
) -> None:
    if argv is not None:
        parser = argparse.ArgumentParser()
        parser.add_argument("--output-dir", metavar="PATH")
        args = parser.parse_args(argv)
        if args.output_dir:
            output_dir = Path(args.output_dir)
    src = config_dir if config_dir is not None else Path.cwd()
    config = load_config(src)
    agents, machines, _aliases = _legacy_settings(config)
    dst = output_dir if output_dir is not None else src
    if output_dir is not None:
        dst.mkdir(parents=True, exist_ok=True)
        print(f"Test mode: writing to {dst} (source module files unchanged)")
    print(f"Compiling AGENTS.md + {len(agents)} agents × {len(machines)} machines...")
    for name, changed in render_to_directory(src, dst).items():
        print(f"  {'compiled' if changed else 'unchanged'} -> {dst / name}")
    print("Done.")
